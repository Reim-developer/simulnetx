#!/usr/bin/env python3
"""Generate simulnetx's reflect_generated.hxx.

Internal tooling for maintainers: this script is NOT part of the library
build (CMake never runs it) and is NOT installed. It exists for one reason:
C++ structured bindings cannot be indexed, so each supported field count
needs its own spelled-out `auto&& [f0, f1, ...]` overload, and writing 200
of those by hand is not an option. This script generates them.

Usage (from the repo root):
    python3 tools/generate_reflect.py --cap 200 \
        --output include/simulnetx/detail/reflect_generated.hxx

    --cap N       Maximum field count to support (default: 200).
                  Raising the cap also requires updating the bound in the
                  `reflectable` concept in include/simulnetx/reflect.hxx
                  (`count_paren<T>() <= CAP`) and the probe range there
                  (`make_index_sequence<CAP + 2>`).
    --output PATH Write the header to PATH instead of stdout.

The script is fully typed (run `python3 -m mypy --strict` on it if mypy is
available). Regenerating with the same cap reproduces the checked-in file
byte-for-byte.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path

DEFAULT_CAP: int = 200

HEADER: str = """// Generated by tools/generate_reflect.py (internal tooling). DO NOT EDIT BY HAND.
// Regenerate with:
//   python3 tools/generate_reflect.py --cap 200 --output include/simulnetx/detail/reflect_generated.hxx
//
// Per-arity structured-binding machinery for simulnetx::reflect:
// to_tuple_impl decomposes an aggregate into a tuple of references,
// and has_reference_field_tag detects reference members via decltype
// of the bindings (a reference member's binding has reference type,
// a value member's does not). Both are needed because structured
// bindings cannot be indexed: each arity needs its own spelling.

#pragma once

#include <cstddef>
#include <tuple>
#include <type_traits>
#include <utility>

namespace simulnetx::reflect::detail {
"""

ARITY_0: str = """// Arity 0: decompose into a tuple of references.
template <typename T>
constexpr auto to_tuple_impl(T&&, std::integral_constant<std::size_t, 0>) {
    return std::tuple<>{};
}
"""

ARITY_0_REF: str = """// Arity 0: reference-member detection for the serializer backstop.
template <typename T>
constexpr std::false_type has_reference_field_tag(T&, std::integral_constant<std::size_t, 0>);
"""

NAMESPACE_CLOSE: str = "}  // namespace simulnetx::reflect::detail\n"


@dataclass(frozen=True)
class Config:
    """Parsed command-line configuration."""

    cap: int = DEFAULT_CAP
    output: Path | None = None


def build_parser() -> argparse.ArgumentParser:
    """Build the command-line parser."""
    parser = argparse.ArgumentParser(
        description="Generate simulnetx's reflect_generated.hxx."
    )
    parser.add_argument(
        "--cap",
        type=int,
        default=DEFAULT_CAP,
        help=f"maximum field count to support (default: {DEFAULT_CAP})",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="write the header to this file instead of stdout",
    )
    return parser


def parse_args(argv: list[str] | None) -> Config:
    """Parse argv into a Config, exiting with an error on bad input."""
    parser = build_parser()
    args: argparse.Namespace = parser.parse_args(argv)
    cap: int = args.cap
    if cap < 0:
        parser.error("--cap must be >= 0")
    output: Path | None = args.output
    return Config(cap=cap, output=output)


def fields(n: int) -> str:
    """Binding names for an arity-n structured binding: "f0, f1, ..."."""
    return ", ".join(f"f{i}" for i in range(n))


def to_tuple_block(n: int) -> str:
    """The to_tuple_impl overload that decomposes an n-field aggregate."""
    names: str = fields(n)
    return f"""// Arity {n}: decompose into a tuple of references.
template <typename T>
constexpr auto to_tuple_impl(T&& obj, std::integral_constant<std::size_t, {n}>) {{
    auto&& [{names}] = std::forward<T>(obj);
    return std::forward_as_tuple({names});
}}
"""


def has_reference_block(n: int) -> str:
    """The has_reference_field_tag overload for an n-field aggregate.

    The (void) casts silence MSVC C4189: the bindings are only used in
    decltype, which MSVC does not count as a reference, and /WX promotes
    the warning to an error (C2220). The casts are inside a lambda that is
    only ever invoked in an unevaluated context, so they never execute.
    """
    names: str = fields(n)
    checks: str = " || ".join(
        f"std::is_reference_v<decltype(f{i})>" for i in range(n)
    )
    voids: str = " ".join(f"(void)f{i};" for i in range(n))
    return f"""// Arity {n}: reference-member detection for the serializer backstop.
template <typename T>
constexpr auto has_reference_field_tag(T&, std::integral_constant<std::size_t, {n}>)
    -> decltype([](T& u) {{
           auto& [{names}] = u;
           {voids}
           return std::bool_constant<({checks})>{{}};
       }}(std::declval<T&>()));
"""


def generate(cap: int) -> str:
    """Generate the full header text for the given arity cap."""
    blocks: list[str] = [HEADER, ARITY_0, ARITY_0_REF]
    for n in range(1, cap + 1):
        blocks.append(to_tuple_block(n))
        blocks.append(has_reference_block(n))
    blocks.append(NAMESPACE_CLOSE)
    return "\n".join(blocks)


def main(argv: list[str] | None = None) -> int:
    """Entry point: parse args, generate, write to file or stdout."""
    config: Config = parse_args(argv)
    text: str = generate(config.cap)
    if config.output is not None:
        config.output.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
